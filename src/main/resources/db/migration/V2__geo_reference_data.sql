-- Reference data: the 58 Algerian wilayas, one seed commune each, and
-- indicative delivery pricing per carrier.
--
-- Prices are realistic placeholders, not a live tariff. Update them with a new
-- migration when the carriers publish changes; never edit an applied migration.

CREATE TABLE wilaya (
    code       SMALLINT     PRIMARY KEY,
    name_fr    VARCHAR(64)  NOT NULL,
    name_ar    VARCHAR(64)  NOT NULL,
    is_south   BOOLEAN      NOT NULL DEFAULT FALSE,

    CONSTRAINT ck_wilaya_code CHECK (code BETWEEN 1 AND 58)
);

CREATE TABLE commune (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wilaya_code  SMALLINT     NOT NULL REFERENCES wilaya (code),
    name         VARCHAR(120) NOT NULL,
    has_stopdesk BOOLEAN      NOT NULL DEFAULT FALSE,

    CONSTRAINT uk_commune_name UNIQUE (wilaya_code, name)
);

CREATE INDEX idx_commune_wilaya ON commune (wilaya_code);

CREATE TABLE delivery_fee (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrier         VARCHAR(32)    NOT NULL,
    wilaya_code     SMALLINT       NOT NULL REFERENCES wilaya (code),
    home_price      NUMERIC(10, 2) NOT NULL,
    stopdesk_price  NUMERIC(10, 2) NOT NULL,

    CONSTRAINT uk_fee_carrier_wilaya UNIQUE (carrier, wilaya_code),
    CONSTRAINT ck_fee_carrier CHECK (carrier IN ('YALIDINE', 'ZREXPRESS', 'NOEST')),
    CONSTRAINT ck_fee_positive CHECK (home_price >= 0 AND stopdesk_price >= 0)
);

